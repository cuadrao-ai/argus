"""Write the Cuadrao baseline migration from a database that ran the full history.

    python3 docs/reports/evidence/1890-baseline/build_baseline.py <db-container> <output.sql>

<db-container> is the local Supabase database container after every file in
supabase/migrations_archive/ and the drop migration ran on it. The script dumps
`public` and `argus_private` with the container's own pg_dump and adds what a
schema dump leaves out: extensions, default privileges, seed rows, storage
buckets, triggers on auth tables and the event trigger. It refuses a database
whose tables hold rows it does not know how to carry.
"""

from __future__ import annotations

import re
import subprocess
import sys

SCHEMAS = ("public", "argus_private")

# Rows a migration inserted that live code needs, as the statement that makes them.
# Rows from supabase/seed.sql are local QA fixtures and stay there.
SEED_STATEMENTS = {
    "public.business_receipt_activity_baseline": (
        "insert into public.business_receipt_activity_baseline (singleton) values (true);"
    ),
    "argus_private.business_custody_deferred_keys": None,  # dumped as rows
}
SEED_SQL_TABLES = {"public.private_alpha_allowlist"}

HEADER = """\
-- One Cuadrao baseline (#1890). It replaces every file now in
-- supabase/migrations_archive/. Generated by
-- docs/reports/evidence/1890-baseline/build_baseline.py. Never edit it; change the
-- schema with a new migration.
set local lock_timeout = '5s';
set local statement_timeout = '60s';
set local check_function_bodies = false;
select pg_catalog.set_config('search_path', '', true);
"""


def run(container: str, *args: str) -> str:
    # An empty search path makes every name in the output schema-qualified.
    # Bytes, decoded strictly: a string literal in the dump can hold a raw carriage
    # return or tab, which universal newlines and str.splitlines() would lose.
    return subprocess.run(
        ["docker", "exec", "-e", "PGOPTIONS=-c search_path=", container, *args],
        check=True, capture_output=True,
    ).stdout.decode("utf-8")  # fmt: skip


def query(container: str, sql: str) -> list[str]:
    out = run(container, "psql", "-U", "supabase_admin", "-d", "postgres", "-XAtc", sql)
    return [line for line in out.split("\n") if line]


def schema_dump(container: str) -> str:
    args = ["pg_dump", "-U", "supabase_admin", "-d", "postgres", "--schema-only", "--no-owner"]
    for schema in SCHEMAS:
        args += ["-n", schema]
    text = run(container, *args)
    body = text[text.index("CREATE SCHEMA argus_private;") :]
    body = body[: body.index("--\n-- PostgreSQL database dump complete")]
    body = re.sub(r"^--\n-- Name: .*\n--\n", "", body, flags=re.MULTILINE)
    drop = (
        re.compile(r"^\\(un)?restrict "),
        re.compile(r"^CREATE SCHEMA public;$"),
        re.compile(r"^COMMENT ON SCHEMA public IS "),
        re.compile(r"^ALTER DEFAULT PRIVILEGES FOR ROLE supabase_admin "),
    )
    lines = [line for line in body.split("\n") if not any(p.match(line) for p in drop)]
    return re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).strip() + "\n"


def extensions(container: str) -> list[str]:
    return query(
        container,
        "select format('create extension if not exists %I with schema %I;', extname,"
        " extnamespace::regnamespace) from pg_extension where extname <> 'plpgsql' order by 1",
    )


# The image grants the API roles on every new object in public. The dump states
# each object's grants against an empty default, so the baseline empties the
# default first; the dump's own ALTER DEFAULT PRIVILEGES lines set the final one.
EMPTY_DEFAULT_PRIVILEGES = [
    f"alter default privileges for role postgres in schema public revoke all on {kind}"
    " from postgres, anon, authenticated, service_role;"
    for kind in ("tables", "sequences", "functions")
]


def seed_rows(container: str) -> list[str]:
    tables = query(
        container,
        "select n.nspname || '.' || c.relname from pg_class c"
        " join pg_namespace n on n.oid = c.relnamespace"
        " where n.nspname in ('public', 'argus_private') and c.relkind in ('r', 'p')"
        " and c.reltuples <> 0 order by 1",
    )
    populated = [
        t for t in tables if query(container, f"select exists (select from {t})") == ["t"]
    ]
    unknown = sorted(set(populated) - set(SEED_STATEMENTS) - SEED_SQL_TABLES)
    if unknown:
        raise SystemExit(f"rows with no seed rule: {unknown}")
    out = []
    for table, statement in sorted(SEED_STATEMENTS.items()):
        if statement is not None:
            out.append(statement)
            continue
        dump = run(
            container, "pg_dump", "-U", "supabase_admin", "-d", "postgres", "--data-only",
            "--column-inserts", "-t", table,
        )  # fmt: skip
        out += [line for line in dump.split("\n") if line.startswith("INSERT INTO ")]
    return out


def buckets(container: str) -> list[str]:
    return query(
        container,
        "select format('insert into storage.buckets (id, name, public, file_size_limit,"
        " allowed_mime_types) values (%L, %L, %L, %s, %L);', id, name, public,"
        " coalesce(file_size_limit::text, 'null'), allowed_mime_types)"
        " from storage.buckets order by id",
    )


def platform_triggers(container: str) -> list[str]:
    return query(
        container,
        "select pg_get_triggerdef(t.oid) || ';' from pg_trigger t"
        " join pg_class c on c.oid = t.tgrelid join pg_proc p on p.oid = t.tgfoid"
        " where not t.tgisinternal"
        " and c.relnamespace::regnamespace::text not in ('public', 'argus_private')"
        " and p.pronamespace::regnamespace::text in ('public', 'argus_private')"
        " order by c.oid::regclass::text, t.tgname",
    )


def event_triggers(container: str) -> list[str]:
    return query(
        container,
        "select format('create event trigger %I on %s%s execute function %s();', evtname,"
        " evtevent, case when evttags is null then '' else ' when tag in (' ||"
        " (select string_agg(quote_literal(tag), ', ') from unnest(evttags) tag) || ')' end,"
        " evtfoid::regproc) from pg_event_trigger"
        " where evtfoid in (select oid from pg_proc"
        " where pronamespace::regnamespace::text in ('public', 'argus_private')) order by evtname",
    )


def main() -> None:
    container, output = sys.argv[1], sys.argv[2]
    parts = [
        HEADER,
        "\n".join(extensions(container)) + "\n",
        "\n".join(EMPTY_DEFAULT_PRIVILEGES) + "\n",
        schema_dump(container),
        "\n".join(seed_rows(container)) + "\n",
        "\n".join(buckets(container)) + "\n",
        "\n".join(platform_triggers(container)) + "\n",
        # Last, so it does not enable row security on tables the history left without it.
        "\n".join(event_triggers(container)) + "\n",
    ]
    with open(output, "w", encoding="utf-8", newline="") as handle:
        handle.write("\n".join(parts))


if __name__ == "__main__":
    main()
