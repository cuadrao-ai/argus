from __future__ import annotations

import hashlib
import json
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

import psycopg
from loguru import logger

ROOT = Path(__file__).resolve().parents[4]
EVIDENCE = ROOT / 'docs/reports/evidence/production-reset'
SQL = ROOT / 'scripts/ops/production_reset'


def main() -> None:
    baseline_path = ROOT / 'supabase/migrations/20261110160000_cuadrao_baseline.sql'
    expected_rls = set(re.findall(r'ALTER TABLE ([\w.]+) ENABLE ROW LEVEL SECURITY;', baseline_path.read_text()))
    actual_rls = set(re.findall(r"'((?:public|argus_private)\.[a-z_]+)'", (SQL / 'verify.sql').read_text()))
    assert expected_rls == actual_rls, (expected_rls - actual_rls, actual_rls - expected_rls)
    verify = (SQL / 'verify.sql').read_text()
    body = 'DO $verify$' + verify.split('DO $verify$', 1)[1].split('$verify$;', 1)[0] + '$verify$;'
    with psycopg.connect('postgresql://postgres:postgres@127.0.0.1:59622/postgres') as db:
        rows = db.execute('''select n.nspname, count(*) from pg_proc p
          join pg_namespace n on n.oid=p.pronamespace where n.nspname in ('public','argus_private')
          and not exists(select from pg_depend d where d.classid='pg_proc'::regclass
            and d.objid=p.oid and d.deptype='e') group by 1 order by 1''').fetchall()
        assert rows == [('argus_private', 99), ('public', 63)], rows
        assert db.execute("select count(*) from pg_policies where schemaname='public'").fetchone()[0] == 134
        for mutation, expected_error in (
            ('alter table public.profiles disable row level security', 'lacks RLS'),
            ("create function public.reset_unexpected() returns int language sql as 'select 1'", 'Expected 63 public functions'),
        ):
            db.execute(mutation)
            try:
                db.execute(body)
            except psycopg.Error as error:
                assert expected_error in error.diag.message_primary
                logger.info('Verifier refused mutation: {}', error.diag.message_primary)
            else:
                raise AssertionError('Verifier accepted a mutated baseline')
            finally:
                db.rollback()
        db.execute(body)
    inventory = (SQL / 'inventory.sql').read_text()
    query = 'SELECT n.nspname AS table_schema' + inventory.split('SELECT n.nspname AS table_schema', 1)[1].split('\nSELECT e.evtname', 1)[0]
    with psycopg.connect('postgresql://postgres:postgres@127.0.0.1:59612/postgres') as db:
        cursor = db.execute(query)
        columns = [column.name for column in cursor.description]
        triggers = [dict(zip(columns, row, strict=True)) for row in cursor.fetchall()]
    lines = ['# Trigger appendix for the reset runbook', '',
             'Generated by reference.py from inventory.sql on the disposable full-history stack.',
             'Every affected table trigger is listed below. Retained platform triggers are marked.',
             'These are local names, not an observation of production. Internal numeric suffixes vary.',
             'Lucas must retain the complete production inventory before reset.', '',
             'The app event trigger `ensure_rls`, backed by `public.rls_auto_enable()`, is also dropped.', '',
             '| Table | Trigger | Foreign-key constraint | Reset action |', '| --- | --- | --- | --- |']
    for t in triggers:
        lines.append(f"| `{t['table_schema']}.{t['table_name']}` | `{t['trigger_name']}` | "
                     f"{t['logical_constraint_name'] or ''} | {t['reset_action']} |")
    (EVIDENCE / 'triggers.md').write_text('\n'.join(lines) + '\n')
    files = [*SQL.glob('*.sql'), * (ROOT / 'supabase/migrations').glob('*.sql')]
    (EVIDENCE / 'source-hashes.json').write_text(json.dumps({
        'migration_candidate_sha': subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(),
        'files': {str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest() for path in sorted(files)},
    }, indent=2) + '\n')
    sys.path.insert(0, str(ROOT))
    from scripts.ops.apply_approved_migrations import (
        ApplyError,
        parse_hosted_approval,
        versions_digest,
    )
    versions = ['20261110160000', '20261110160100']
    draft = (ROOT / 'docs/release-manifests/2026-11-10-production-baseline-apply.json').read_text()
    assert json.loads(draft)['versions_sha256'] == versions_digest(versions)
    try:
        parse_hosted_approval(draft, 'a' * 40, versions, [], datetime.now(timezone.utc))
    except ApplyError as error:
        assert 'different candidate' in str(error), error
    else:
        raise AssertionError('NOT APPROVED draft was accepted')
    logger.info('Baseline reference: {} RLS tables, 134 policies, 63 public/99 private functions', len(expected_rls))
    logger.info('Trigger inventory: {} drop candidates, {} retained/review rows',
                sum(t['reset_action'].startswith('drop') for t in triggers),
                sum(not t['reset_action'].startswith('drop') for t in triggers))
    logger.info('Approval draft rejected; versions digest matches both migrations executing')


if __name__ == '__main__':
    main()
