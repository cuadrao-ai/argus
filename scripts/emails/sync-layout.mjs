import { readFileSync, writeFileSync } from "node:fs";
const source = new URL("../../marketing/lib/email/account-layout.ts", import.meta.url);
const destination = new URL("../../web/server/emails/account-layout.generated.ts", import.meta.url);
const webCopy = `import spanish from "../../public/locales/es-419/common.json";
import english from "../../public/locales/en/common.json";
const accountCopy = { "es-419": spanish.account_email, en: english.account_email };`;
const contract = readFileSync(new URL("../../web/lib/email-otp-contract.ts", import.meta.url), "utf8");
const contractDestination = new URL("../../marketing/lib/email/email-otp-contract.generated.ts", import.meta.url);
const contractOutput = `// Generated by scripts/emails/sync-layout.mjs. Edit web/lib/email-otp-contract.ts.\n${contract}`;
const supportContact = JSON.parse(readFileSync(new URL("../../web/argus_display_contract/support_contact.json", import.meta.url), "utf8"));
const supportDestination = new URL("../../marketing/lib/email/support-email.generated.ts", import.meta.url);
const supportOutput = `// Generated by scripts/emails/sync-layout.mjs. Edit web/argus_display_contract/support_contact.json.\nexport const supportEmail = ${JSON.stringify(supportContact.email)};\n`;
const output = `// Generated by scripts/emails/sync-layout.mjs. Edit marketing/lib/email/account-layout.ts.\n${readFileSync(source, "utf8").replace('"./email-otp-contract.generated"', '"../../lib/email-otp-contract"').replace('"./support-email.generated"', '"../../lib/support-email"').replace('import accountCopy from "./account-copy.generated.json";', webCopy)}`;
const copyDestination = new URL("../../marketing/lib/email/account-copy.generated.json", import.meta.url);
const copy = Object.fromEntries(["es-419", "en"].map(locale => {
  const catalog = JSON.parse(readFileSync(new URL(`../../web/public/locales/${locale}/common.json`, import.meta.url), "utf8"));
  const { footer, business_lifecycle, existing_account } = catalog.account_email;
  return [locale, { footer, business_lifecycle, existing_account }];
}));
const copyOutput = JSON.stringify(copy, null, 2) + "\n";
if (process.argv.includes("--check")) {
  if (readFileSync(contractDestination, "utf8") !== contractOutput) throw new Error("Marketing email OTP contract is stale");
  if (readFileSync(supportDestination, "utf8") !== supportOutput) throw new Error("Marketing support address is stale");
  if (readFileSync(destination, "utf8") !== output) throw new Error("Shared email layout copy is stale");
  if (readFileSync(copyDestination, "utf8") !== copyOutput) throw new Error("Marketing email copy is stale");
} else {
  writeFileSync(contractDestination, contractOutput);
  writeFileSync(supportDestination, supportOutput);
  writeFileSync(destination, output);
  writeFileSync(copyDestination, copyOutput);
}
