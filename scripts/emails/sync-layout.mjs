import { readFileSync, writeFileSync } from "node:fs";
const source = new URL("../../marketing/lib/email/account-layout.ts", import.meta.url);
const destination = new URL("../../web/server/emails/account-layout.generated.ts", import.meta.url);
const output = `// Generated by scripts/emails/sync-layout.mjs. Edit marketing/lib/email/account-layout.ts.\n${readFileSync(source, "utf8")}`;
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== output) throw new Error("Shared email layout copy is stale");
} else writeFileSync(destination, output);
