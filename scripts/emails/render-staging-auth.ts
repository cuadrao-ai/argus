import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { parseArgs } from "node:util";
import { emailExpiry } from "../../web/server/emails/expiry";

const { values } = parseArgs({
  options: {
    check: { type: "boolean", default: false },
    output: { type: "string" },
    "expiry-seconds": { type: "string", default: "3600" },
  },
  strict: true,
  allowPositionals: false,
});
const check = values.check;
const expiryInput = values["expiry-seconds"]!;
if (!/^[0-9]+$/.test(expiryInput)) throw new Error("--expiry-seconds requires a positive integer");
const expirySeconds = Number(expiryInput);
emailExpiry(expirySeconds);
if (values.output === "") throw new Error("--output requires a folder");
const destination = values.output === undefined
  ? new URL("../../temp/generated-auth-email/", import.meta.url)
  : pathToFileURL(`${resolve(values.output)}/`);

const sync = Bun.spawnSync([process.execPath, new URL("./sync-layout.mjs", import.meta.url).pathname, ...(check ? ["--check"] : [])], { stdout: "inherit", stderr: "inherit" });
if (sync.exitCode !== 0) throw new Error("Shared email sources did not sync");
const { buildDashboardAuthPaste } = await import("../../web/server/emails/auth-paste");
const records = await buildDashboardAuthPaste(expirySeconds);
const artifacts = new Map<string, string>();
for (const record of records) {
  artifacts.set(`${record.file}.html`, record.html);
  artifacts.set(`${record.file}.txt`, record.text);
  artifacts.set(`${record.file}.subject.txt`, `${record.subject}\n`);
}
artifacts.set("manifest.json", `${JSON.stringify({
  generated: "Generated by scripts/emails/render-staging-auth.ts. Do not edit artifacts. Regenerate from repo sources.",
  expirySeconds,
  templates: records.map(record => ({
    slot: record.file,
    subjectField: record.subjectField,
    bodyField: record.bodyField,
    subject: `${record.file}.subject.txt`,
    html: `${record.file}.html`,
    text: `${record.file}.txt`,
  })),
}, null, 2)}\n`);
if (!check) await mkdir(destination, { recursive: true });
for (const [file, content] of artifacts) {
  const path = new URL(file, destination);
  if (check) {
    if (await readFile(path, "utf8") !== content) throw new Error(`Generated Auth artifact is stale: ${file}`);
  } else await writeFile(path, content);
}
console.log(check ? "Generated Auth artifacts match repo sources." : "Rendered Auth artifacts locally. No configuration changed and no email was sent.");
